"""Live evaluation of the AI answer mode (needs OPENAI_API_KEY; costs a few cents).

Runs every labelled question through the deployed configuration (hybrid
retrieval + chat model) and measures, per answer:
  - mode (llm / abstained / model_error)
  - whether the expected fact (evidence keyword) appears in the answer
  - whether a cited source is on an expected page
  - grounding-screen verdict
  - tokens and estimated cost
Writes eval/LLM_RESULTS.md and eval/llm_results.json.

Usage:  OPENAI_API_KEY=... python scripts/evaluate_llm.py
"""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
import json
import os
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from Code.course_core import CourseAssistant  # noqa: E402

QUESTIONS = ROOT / "eval" / "questions.jsonl"


def flat(text: str) -> str:
    return re.sub(r"\s+", " ", text).lower()


def fact_in_answer(keyword: str, answer: str) -> bool:
    """Keyword match tolerant of number formatting and German/English unit spelling."""
    a = flat(answer)
    k = flat(keyword)
    if k in a:
        return True
    nums = re.findall(r"\d+(?:[.,]\d+)*", k)
    if nums:  # numeric facts: every number must appear (30.000 == 30,000 == 30000)
        norm = lambda s: re.sub(r"[.,]", "", s)
        answer_nums = {norm(n) for n in re.findall(r"\d+(?:[.,]\d+)*", a)}
        return all(norm(n) in answer_nums for n in nums)
    return False


def main() -> int:
    if not os.getenv("OPENAI_API_KEY"):
        print("OPENAI_API_KEY is not set; nothing to evaluate.")
        return 2
    questions = [json.loads(l) for l in QUESTIONS.read_text(encoding="utf-8").splitlines() if l]
    assistant = CourseAssistant(ROOT / "data")
    rows = []
    for q in questions:
        r = assistant.ask(q["question"], q["department"])
        cited_ok = any([s["document"], s["page"]] in q["expected"] for s in r["sources"])
        usage = r.get("usage") or {}
        rows.append({
            "id": q["id"], "kind": q["kind"], "language": q["language"],
            "answerable": q["answerable"], "mode": r["mode"],
            "retrieval_mode": r["retrieval_mode"],
            "fact_in_answer": q["answerable"] and fact_in_answer(q["evidence_keyword"], r["answer"]),
            "cited_expected_page": q["answerable"] and cited_ok,
            "grounding": (r.get("grounding") or {}).get("verdict"),
            "prompt_tokens": usage.get("prompt_tokens", 0),
            "completion_tokens": usage.get("completion_tokens", 0),
            "cost_usd": usage.get("estimated_cost_usd") or 0.0,
            "answer": r["answer"], "warning": r.get("warning"),
        })
        print(f"{q['id']}: {r['mode']} fact={rows[-1]['fact_in_answer']} "
              f"cite={rows[-1]['cited_expected_page']} grounding={rows[-1]['grounding']}", flush=True)

    ans = [r for r in rows if r["answerable"]]
    una = [r for r in rows if not r["answerable"]]
    llm = [r for r in ans if r["mode"] == "llm"]
    n = len(ans) or 1
    stats = dict(assistant.stats)
    embed_cost = stats.get("embedding_tokens", 0) * 0.02 / 1_000_000
    summary = {
        "run_at_utc": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M"),
        "chat_model": assistant.chat_model,
        "embedding_model": assistant.embedding_model if assistant.vector_enabled else None,
        "answerable": len(ans), "unanswerable": len(una),
        "answered_by_llm": round(len(llm) / n, 3),
        "fact_in_answer": round(sum(r["fact_in_answer"] for r in ans) / n, 3),
        "cites_expected_page": round(sum(r["cited_expected_page"] for r in ans) / n, 3),
        "grounding_passed_of_llm_answers": round(
            sum(r["grounding"] == "passed" for r in llm) / (len(llm) or 1), 3),
        "false_abstention": round(sum(r["mode"] == "abstained" for r in ans) / n, 3),
        "correct_abstention": round(sum(r["mode"] == "abstained" for r in una) / (len(una) or 1), 3),
        "model_errors": sum(r["mode"] == "model_error" for r in rows),
        "chat_calls": stats.get("chat_calls", 0),
        "abstained_before_model": stats.get("abstained_before_model", 0),
        "chat_cost_usd": round(sum(r["cost_usd"] for r in rows), 5),
        "embedding_cost_usd": round(embed_cost, 5),
        "avg_cost_per_llm_answer_usd": round(sum(r["cost_usd"] for r in llm) / (len(llm) or 1), 6),
    }
    print(json.dumps(summary, indent=2))
    (ROOT / "eval" / "llm_results.json").write_text(
        json.dumps({"summary": summary, "rows": rows}, indent=2, ensure_ascii=False), encoding="utf-8")
    (ROOT / "eval" / "LLM_RESULTS.md").write_text(render(summary, rows), encoding="utf-8")
    return 0


def render(s, rows) -> str:
    pct = lambda x: f"{x * 100:.1f}%"
    lines = [
        "# Live AI-mode evaluation (generated by `scripts/evaluate_llm.py`)",
        "",
        f"Run {s['run_at_utc']} UTC with `{s['chat_model']}`"
        + (f" and `{s['embedding_model']}` (hybrid retrieval)" if s["embedding_model"] else "")
        + f" on the same {s['answerable'] + s['unanswerable']} labelled questions as `eval/RESULTS.md` "
        "(AI-drafted dev set; see the caveats there). One run; model output can vary between runs.",
        "",
        "| Metric | Value |", "|---|---|",
        f"| Answerable questions answered by the model | {pct(s['answered_by_llm'])} |",
        f"| Expected fact present in the answer | {pct(s['fact_in_answer'])} |",
        f"| Answer cites the expected page | {pct(s['cites_expected_page'])} |",
        f"| Grounding screen passed (model answers) | {pct(s['grounding_passed_of_llm_answers'])} |",
        f"| False abstention (answerable) | {pct(s['false_abstention'])} |",
        f"| Correct abstention (unanswerable, n={s['unanswerable']}) | {pct(s['correct_abstention'])} |",
        f"| Provider errors | {s['model_errors']} |",
        f"| Model calls / abstained before any call | {s['chat_calls']} / {s['abstained_before_model']} |",
        f"| Total cost (chat + embeddings, estimated) | ${s['chat_cost_usd'] + s['embedding_cost_usd']:.4f} |",
        f"| Average cost per model answer | ${s['avg_cost_per_llm_answer_usd']:.6f} |",
        "",
        "\"Expected fact present\" is an automatic keyword/number check, so a correct paraphrase "
        "can count as a miss. Questions that did not pass are listed below for manual review.",
        "",
        "## Answers that missed the expected fact or citation",
        "",
    ]
    misses = [r for r in rows if r["answerable"] and not (r["fact_in_answer"] and r["cited_expected_page"])]
    misses += [r for r in rows if not r["answerable"] and r["mode"] != "abstained"]
    for r in misses:
        answer = r["answer"].replace("\n", " ")
        lines.append(f"- `{r['id']}` ({r['mode']}, fact={r['fact_in_answer']}, "
                     f"cite={r['cited_expected_page']}, grounding={r['grounding']}): {answer[:300]}")
    if not misses:
        lines.append("- None.")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    raise SystemExit(main())
