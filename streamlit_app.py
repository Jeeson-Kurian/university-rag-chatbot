"""Course Compass student interface.

Default: runs the engine in-process (one command, also works on Streamlit
Community Cloud). Set UNIVERSITY_API_URL to call a separately running FastAPI
service instead.
"""
from __future__ import annotations

import os

import streamlit as st

from Code.course_core import DEPARTMENTS, CourseAssistant

API_URL = os.getenv("UNIVERSITY_API_URL", "").rstrip("/")
EXAMPLES = {
    "AIandCybersecurity": [
        "How many ECTS credits does the Master's thesis comprise?",
        "What English language level is required for applicants whose first language is not English?",
        "Who won the last football world cup?",
    ],
    "Informatics": [
        "How many hours must the internship last?",
        "Which specialist subjects can students select?",
        "What is the tuition fee for non-EU students?",
    ],
    "Business": [
        "How long should the internship last?",
        "How many ECTS credits are required in open electives?",
        "How much does a student parking permit cost?",
    ],
    "English": [
        "What English level is required for applicants whose first language is not English?",
        "Wie viele ECTS-AP umfasst die Masterarbeit?",
        "What is the Neptune spacecraft launch timetable?",
    ],
}
MODE_TEXT = {
    "llm": (":green[AI answer]", "Generated by the language model from the cited excerpts only."),
    "extractive": (":blue[Extractive answer]", "Sentences copied from the documents. No language model was called."),
    "abstained": (":orange[No answer]", "The documents do not contain enough evidence, so nothing was generated."),
    "model_error": (":red[Model unavailable]", "The model provider failed. Retry later."),
}
STATUS_TEXT = {
    "supported": ":green[supported]",
    "uncited": ":orange[no citation]",
    "number_not_in_evidence": ":red[number not found in cited text]",
    "weak_support": ":orange[weak match with cited text]",
}


@st.cache_resource(show_spinner="Indexing curriculum documents…")
def local_assistant() -> CourseAssistant:
    if not os.getenv("OPENAI_API_KEY"):
        try:  # Streamlit Community Cloud secrets
            key = st.secrets.get("OPENAI_API_KEY")
            if key:
                os.environ["OPENAI_API_KEY"] = key
        except Exception:
            pass
    return CourseAssistant()


def ask(question: str, department: str) -> dict:
    if API_URL:
        import requests
        response = requests.post(f"{API_URL}/ask", json={"department": department,
                                                         "question": question}, timeout=45)
        response.raise_for_status()
        return response.json()
    return local_assistant().ask(question, department)


def set_question(text: str) -> None:
    st.session_state["question"] = text


st.set_page_config(page_title="Course Compass", page_icon="🧭", layout="centered")
st.title("🧭 Course Compass")
st.caption("Ask your curriculum. Every answer links to the page it came from, "
           "and the assistant says so when the documents don't cover a question.")

with st.sidebar:
    st.subheader("How it works")
    st.markdown(
        "1. **BM25 search** inside the selected study area only, with an English↔German "
        "curriculum glossary.\n"
        "2. **Evidence gate**: if too little of your question is covered, it abstains "
        "*before* calling any model (no cost, no guessing).\n"
        "3. **Answer**: a citation-constrained LLM answer when a key is configured, "
        "otherwise a free extractive answer.\n"
        "4. **Grounding check**: every sentence is screened against the cited text; "
        "numbers that don't appear in the source are flagged.")
    if not API_URL:
        engine = local_assistant()
        if engine.client is None:
            st.info("Free mode: no API key configured, answers are extractive.")
        else:
            st.success(f"AI mode: {engine.chat_model}"
                       + (f" + {engine.embedding_model}" if engine.vector_enabled else ""))
        if engine.stats:
            st.caption("Session counters: " + ", ".join(f"{k}={v}" for k, v in sorted(engine.stats.items())))
    st.caption("Not an official university service. Curricula can change; confirm "
               "important decisions with the official documents.")

department = st.selectbox("Study area", list(DEPARTMENTS), format_func=lambda k: DEPARTMENTS[k])
st.write("Try one:")
for column, example in zip(st.columns(3), EXAMPLES[department]):
    column.button(example, key=f"ex-{department}-{example}", on_click=set_question,
                  args=(example,), use_container_width=True)
question = st.text_area("Your question", key="question", max_chars=800, height=100,
                        placeholder="How many ECTS credits does the Master's thesis comprise?")

if st.button("Find the answer", type="primary", disabled=len(question.strip()) < 4):
    try:
        with st.spinner("Searching the curriculum…"):
            result = ask(question.strip(), department)
    except Exception:
        st.error("The assistant is unavailable. If you use API mode, start the FastAPI server and retry.")
        st.stop()

    label, explanation = MODE_TEXT.get(result["mode"], (result["mode"], ""))
    st.markdown(f"#### {label}")
    st.caption(explanation)
    st.markdown(result["answer"])
    if result.get("warning"):
        st.warning(result["warning"])

    grounding = result.get("grounding")
    if grounding:
        with st.expander(f"Grounding check: {grounding['sentences_supported']}/"
                         f"{grounding['sentences_checked']} sentences supported"):
            for row in grounding["sentences"]:
                st.markdown(f"{STATUS_TEXT.get(row['status'], row['status'])} · "
                            f"{', '.join(row['citations']) or 'no citation'} · "
                            f"term match {row['term_support']:.0%}")
                st.caption(row["sentence"])
            st.caption(f"Method: {grounding['method']}.")

    if result.get("sources"):
        st.markdown("#### Sources")
        for source in result["sources"]:
            page = f", page {source['page']}" if source.get("page") else ""
            with st.expander(f"[{source['id']}] {source['document']}{page}"):
                st.write(source["excerpt"])

    meta = [f"retrieval: {result['retrieval_mode']}"]
    if result.get("model"):
        meta.append(f"model: {result['model']}")
    usage = result.get("usage") or {}
    if usage.get("estimated_cost_usd") is not None:
        meta.append(f"≈ ${usage['estimated_cost_usd']:.5f} "
                    f"({usage['prompt_tokens']}+{usage['completion_tokens']} tokens)")
    if result.get("cached"):
        meta.append("served from cache (no new model call)")
    st.caption(" · ".join(meta))
